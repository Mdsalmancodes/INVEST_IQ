@dataclass(slots=True)
class Recommendation:
    """
    Final recommendation generated by the Hybrid Decision Engine.
    """

    id: PredictionRunId
    symbol: str
    verdict: Verdict
    confidence: Confidence
    price_forecast: float
    sentiment_score: float
    explainability: ExplainabilityPayload
    data_quality: DataQuality
    contributing_models: tuple[ModelFamily, ...]
    created_at: datetime

    @classmethod
    def create(
        cls,
        symbol: str,
        verdict: Verdict,
        confidence: Confidence,
        price_forecast: float,
        sentiment_score: float,
        explainability: ExplainabilityPayload,
        data_quality: DataQuality,
        contributing_models: tuple[ModelFamily, ...],
    ) -> Recommendation:

        if not symbol or not symbol.strip():
            raise ValueError(
                "Recommendation symbol must not be empty"
            )

        if not contributing_models:
            raise ValueError(
                "Recommendation requires at least one contributing model"
            )

        if not (
            -1.0
            <= sentiment_score
            <= 1.0
        ):
            raise ValueError(
                "sentiment_score must be in [-1.0, 1.0], "
                f"got {sentiment_score}"
            )

        return cls(
            id=PredictionRunId.new(),
            symbol=symbol.upper().strip(),
            verdict=verdict,
            confidence=confidence,
            price_forecast=float(price_forecast),
            sentiment_score=float(sentiment_score),
            explainability=explainability,
            data_quality=data_quality,
            contributing_models=contributing_models,
            created_at=datetime.now(UTC),
        )


