@dataclass(slots=True)
class PredictionRun:
    """
    Immutable record of a completed hybrid prediction.

    A PredictionRun contains all model forecasts that contributed
    to the final ensemble result.
    """

    id: PredictionRunId
    symbol: str
    member_forecasts: tuple[Forecast, ...]
    ensemble_price: float
    ensemble_confidence: Confidence
    data_quality: DataQuality
    explainability: ExplainabilityPayload
    created_at: datetime
    actual_price: float | None = field(default=None)

    @classmethod
    def create(
        cls,
        symbol: str,
        member_forecasts: tuple[Forecast, ...],
        ensemble_price: float,
        ensemble_confidence: Confidence,
        data_quality: DataQuality,
        explainability: ExplainabilityPayload,
    ) -> PredictionRun:

        if not symbol or not symbol.strip():
            raise ValueError(
                "PredictionRun symbol must not be empty"
            )

        if not member_forecasts:
            raise ValueError(
                "PredictionRun requires at least one member Forecast"
            )

        return cls(
            id=PredictionRunId.new(),
            symbol=symbol.upper().strip(),
            member_forecasts=member_forecasts,
            ensemble_price=float(ensemble_price),
            ensemble_confidence=ensemble_confidence,
            data_quality=data_quality,
            explainability=explainability,
            created_at=datetime.now(UTC),
        )

    def record_actual_price(
        self,
        actual_price: float,
    ) -> None:
        """
        Record the actual future market price when available.
        """

        if actual_price <= 0:
            raise ValueError(
                "actual_price must be greater than zero"
            )

        self.actual_price = float(actual_price)

    @property
    def absolute_error(self) -> float | None:

        if self.actual_price is None:
            return None

        return abs(
            self.actual_price - self.ensemble_price
        )


