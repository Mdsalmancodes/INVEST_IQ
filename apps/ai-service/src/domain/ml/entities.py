ModelStatus = str
"""
Supported lifecycle states:

    training
    validating
    canary
    active
    retired
"""


@dataclass(slots=True)
class ModelVersion:
    """
    Metadata for one trained model artifact.

    IMPORTANT:

    ModelVersion is SYMBOL-AWARE.

    Example:

        family = "lstm"
        symbol = "AAPL"

    is a different model version from:

        family = "lstm"
        symbol = "TSLA"

    This is required because INVEST IQ supports multiple stocks.
    """

    id: ModelVersionId

    # Model family:
    # lstm / arima / prophet / random_forest / xgboost
    family: ModelFamily

    # Stock symbol this model was trained for.
    symbol: str

    # Unique human-readable training version.
    version_tag: str

    # When training completed.
    trained_at: datetime

    # Historical data range used during training.
    training_data_range_start: datetime
    training_data_range_end: datetime

    # Validation metrics produced by the model.
    validation_metrics: dict[str, float]

    # Lifecycle status.
    status: str

    # Path to the trained model artifact.
    artifact_location: str

    # Future canary rollout support.
    rollout_percentage: int = field(default=100)

    @classmethod
    def create(
        cls,
        family: ModelFamily,
        symbol: str,
        version_tag: str,
        training_data_range_start: datetime,
        training_data_range_end: datetime,
        validation_metrics: dict[str, float],
        artifact_location: str,
    ) -> ModelVersion:

        if not symbol or not symbol.strip():
            raise ValueError(
                "ModelVersion symbol must not be empty"
            )

        if not version_tag or not version_tag.strip():
            raise ValueError(
                "ModelVersion version_tag must not be empty"
            )

        if not artifact_location or not artifact_location.strip():
            raise ValueError(
                "ModelVersion artifact_location must not be empty"
            )

        if (
            training_data_range_end
            < training_data_range_start
        ):
            raise ValueError(
                "training_data_range_end cannot be before "
                "training_data_range_start"
            )

        return cls(
            id=ModelVersionId.new(),
            family=family,
            symbol=symbol.upper().strip(),
            version_tag=version_tag,
            trained_at=datetime.now(UTC),
            training_data_range_start=training_data_range_start,
            training_data_range_end=training_data_range_end,
            validation_metrics=validation_metrics,
            status="active",
            artifact_location=artifact_location,
            rollout_percentage=100,
        )

    def retire(self) -> None:
        """
        Retire this model version.
        """

        self.status = "retired"