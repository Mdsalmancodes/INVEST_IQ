"""
Domain entities for the AI/ML bounded context.

INVEST IQ Phase 2.

These entities represent:
- model forecasts
- prediction runs
- sentiment results
- recommendations
- trained model versions

ModelVersion is SYMBOL-AWARE.

A trained model is identified by:

    model family + symbol + version

Example:

    random_forest + AAPL + version_1
    random_forest + TSLA + version_1

This prevents the ModelLoader from accidentally loading a model
trained for another stock.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime

from src.domain.ml.value_objects import (
    Confidence,
    DataQuality,
    ExplainabilityPayload,
    ModelFamily,
    ModelVersionId,
    PredictionRunId,
    SentimentLabel,
    Verdict,
)


# ============================================================================
# FORECAST
# ============================================================================


@dataclass(frozen=True, slots=True)
class HorizonPoint:
    """
    A single forecasted price point for a particular prediction horizon.
    """

    horizon_days: int
    predicted_price: float
    lower_bound: float
    upper_bound: float


@dataclass(slots=True)
class Forecast:
    """
    Forecast generated by one model family for one stock symbol.
    """

    id: PredictionRunId
    symbol: str
    model_family: ModelFamily
    model_version_id: ModelVersionId
    points: tuple[HorizonPoint, ...]
    confidence: Confidence
    data_quality: DataQuality
    created_at: datetime

    @classmethod
    def create(
        cls,
        symbol: str,
        model_family: ModelFamily,
        model_version_id: ModelVersionId,
        points: tuple[HorizonPoint, ...],
        confidence: Confidence,
        data_quality: DataQuality,
    ) -> Forecast:

        if not symbol or not symbol.strip():
            raise ValueError("Forecast symbol must not be empty")

        if not points:
            raise ValueError(
                "Forecast must contain at least one HorizonPoint"
            )

        return cls(
            id=PredictionRunId.new(),
            symbol=symbol.upper().strip(),
            model_family=model_family,
            model_version_id=model_version_id,
            points=points,
            confidence=confidence,
            data_quality=data_quality,
            created_at=datetime.now(UTC),
        )

    def point_for_horizon(
        self,
        horizon_days: int,
    ) -> HorizonPoint | None:

        for point in self.points:
            if point.horizon_days == horizon_days:
                return point

        return None


