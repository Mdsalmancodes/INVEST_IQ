@dataclass(slots=True)
class SentimentScore:
    """
    FinBERT sentiment result for a text item or aggregated symbol sentiment.
    """

    symbol: str
    label: SentimentLabel
    confidence: Confidence
    article_count: int
    created_at: datetime
    source_text: str | None = field(default=None)

    @classmethod
    def create(
        cls,
        symbol: str,
        label: SentimentLabel,
        confidence: Confidence,
        article_count: int = 1,
        source_text: str | None = None,
    ) -> SentimentScore:

        if not symbol or not symbol.strip():
            raise ValueError(
                "SentimentScore symbol must not be empty"
            )

        if article_count < 1:
            raise ValueError(
                f"article_count must be >= 1, got {article_count}"
            )

        return cls(
            symbol=symbol.upper().strip(),
            label=label,
            confidence=confidence,
            article_count=article_count,
            created_at=datetime.now(UTC),
            source_text=source_text,
        )

    @classmethod
    def aggregate(
        cls,
        symbol: str,
        scores: tuple[SentimentScore, ...],
    ) -> SentimentScore:
        """
        Aggregate multiple FinBERT sentiment scores.
        """

        if not scores:
            raise ValueError(
                "Cannot aggregate an empty tuple of SentimentScore"
            )

        target_volume = 10

        label_weights = {
            "positive": 1.0,
            "neutral": 0.0,
            "negative": -1.0,
        }

        weighted_sum = sum(
            label_weights[score.label]
            * score.confidence.value
            for score in scores
        )

        net_score = weighted_sum / len(scores)

        if net_score > 0.15:
            aggregate_label: SentimentLabel = "positive"

        elif net_score < -0.15:
            aggregate_label = "negative"

        else:
            aggregate_label = "neutral"

        volume_confidence = min(
            1.0,
            len(scores) / target_volume,
        )

        return cls.create(
            symbol=symbol,
            label=aggregate_label,
            confidence=Confidence(
                round(volume_confidence, 4)
            ),
            article_count=len(scores),
        )


