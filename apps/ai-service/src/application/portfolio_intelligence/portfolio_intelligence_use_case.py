"""
PortfolioIntelligenceUseCase — Phase 10 Portfolio Intelligence.

Application-layer orchestration for:

    - Portfolio Analytics
    - Portfolio Risk Metrics
    - AI Portfolio Engine
    - Portfolio Optimization
    - AI Recommendations
    - Monte Carlo Simulation

Architecture:

    HTTP/API
        ↓
    Presentation / Dependency Injection
        ↓
    PortfolioIntelligenceUseCase
        ↓
    fetch_holdings_returns()
        ↓
    ┌─────────────────────────────────────────────┐
    │ AnalyticsService                            │
    │ RiskMetricsService                          │
    │ AiPortfolioEngineService                    │
    │ OptimizationService                         │
    │ RecommendationEngineService                 │
    └─────────────────────────────────────────────┘
                       │
                       ▼
             PortfolioIntelligenceResult

Monte Carlo is intentionally exposed through a separate
MonteCarloUseCase because it is independently parameterized
and computationally expensive.

This application layer does not know how ML models are loaded.
AiPortfolioEngineService is injected by the presentation/DI layer.
"""

