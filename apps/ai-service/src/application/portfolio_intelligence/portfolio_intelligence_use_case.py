# ============================================================================
# PORTFOLIO INTELLIGENCE RESULT
# ============================================================================


@dataclass(frozen=True, slots=True)
class PortfolioIntelligenceResult:
    """
    Complete result of the Phase 10 portfolio-intelligence pipeline.

    Attributes
    ----------
    analytics:
        Historical portfolio analytics and health metrics.

    risk_metrics:
        Portfolio risk measurements.

    ai_predictions:
        Forward-looking AI portfolio predictions generated by the
        existing trained ML infrastructure.

    optimization:
        MPT optimization result.

        None when optimization is not mathematically available,
        for example for a single-holding portfolio.

    recommendations:
        Portfolio-level recommendations generated from the
        complete Phase 10 result.
    """

    analytics: PortfolioAnalytics
    risk_metrics: RiskMetrics
    ai_predictions: AiPortfolioPredictions
    optimization: OptimizationResult | None
    recommendations: tuple[Recommendation, ...]


# ============================================================================
# PORTFOLIO INTELLIGENCE USE CASE
# ============================================================================


class PortfolioIntelligenceUseCase:
    """
    Orchestrates the complete Phase 10 portfolio-intelligence pipeline.

    Flow:

        holdings
            ↓
        fetch_holdings_returns()
            ↓
        shared OHLCV + portfolio returns
            ↓
        AnalyticsService
            ↓
        RiskMetricsService
            ↓
        AiPortfolioEngineService
            ↓
        OptimizationService
            ↓
        RecommendationEngineService
            ↓
        PortfolioIntelligenceResult

    The raw OHLCV bars captured during the initial market-data
    operation are passed to AiPortfolioEngineService so that it
    does not perform a second market-data request.

    AiPortfolioEngineService is intentionally injected into this
    application service. Model-loading concerns belong to the
    presentation/dependency-injection layer.
    """

    def __init__(
        self,
        market_data_repository: MarketDataRepository,
        ai_portfolio_engine_service: AiPortfolioEngineService,
        analytics_service: AnalyticsService | None = None,
        risk_metrics_service: RiskMetricsService | None = None,
        optimization_service: OptimizationService | None = None,
        recommendation_engine_service: RecommendationEngineService | None = None,
    ) -> None:
        """
        Initialize the portfolio-intelligence use case.

        Parameters
        ----------
        market_data_repository:
            Repository used to retrieve market OHLCV data.

        ai_portfolio_engine_service:
            Fully configured AI portfolio engine.

            This dependency is required because the AI portfolio
            engine requires a ModelLoader and must be constructed
            by the presentation/dependency-injection layer.

        analytics_service:
            Optional analytics service. A default implementation
            is created when omitted.

        risk_metrics_service:
            Optional risk metrics service. A default implementation
            is created when omitted.

        optimization_service:
            Optional portfolio optimization service. A default
            implementation is created when omitted.

        recommendation_engine_service:
            Optional recommendation engine. A default implementation
            is created when omitted.
        """

        self._market_data_repository = market_data_repository

        self._ai_portfolio_engine_service = (
            ai_portfolio_engine_service
        )

        self._analytics_service = (
            analytics_service
            if analytics_service is not None
            else AnalyticsService()
        )

        self._risk_metrics_service = (
            risk_metrics_service
            if risk_metrics_service is not None
            else RiskMetricsService()
        )

        self._optimization_service = (
            optimization_service
            if optimization_service is not None
            else OptimizationService()
        )

        self._recommendation_engine_service = (
            recommendation_engine_service
            if recommendation_engine_service is not None
            else RecommendationEngineService()
        )

    async def execute(
        self,
        holdings: list[PortfolioHoldingInput],
        lookback_days: int = 400,
    ) -> PortfolioIntelligenceResult:
        """
        Execute the complete Phase 10 portfolio-intelligence pipeline.

        The market data is fetched once and shared between the
        analytics, risk, AI, optimization, and recommendation
        stages.
        """

        # ------------------------------------------------------------------
        # VALIDATION
        # ------------------------------------------------------------------

        if lookback_days <= 0:
            raise ValueError(
                "lookback_days must be greater than zero."
            )

        if not holdings:
            raise ValueError(
                "At least one portfolio holding is required."
            )

        # ------------------------------------------------------------------
        # SHARED MARKET DATA
        # ------------------------------------------------------------------

        bars_by_symbol: dict[
            str,
            tuple[OhlcvBar, ...],
        ] = {}

        data = await fetch_holdings_returns(
            self._market_data_repository,
            holdings,
            lookback_days,
            bars_out=bars_by_symbol,
        )

        # ------------------------------------------------------------------
        # ANALYTICS
        # ------------------------------------------------------------------

        analytics = self._analytics_service.compute(
            data
        )

        # ------------------------------------------------------------------
        # RISK METRICS
        # ------------------------------------------------------------------

        risk_metrics = self._risk_metrics_service.compute(
            data
        )

        # ------------------------------------------------------------------
        # AI PORTFOLIO ENGINE
        # ------------------------------------------------------------------

        ai_predictions = (
            await self._ai_portfolio_engine_service.compute(
                data=data,
                analytics=analytics,
                risk_metrics=risk_metrics,
                bars_by_symbol=bars_by_symbol,
            )
        )

        # ------------------------------------------------------------------
        # PORTFOLIO OPTIMIZATION
        # ------------------------------------------------------------------

        optimization: OptimizationResult | None

        try:
            optimization = self._optimization_service.optimize(
                data
            )
        except InsufficientHoldingsForOptimizationError:
            optimization = None

        # ------------------------------------------------------------------
        # RECOMMENDATIONS
        # ------------------------------------------------------------------

        recommendations = (
            self._recommendation_engine_service.generate(
                analytics,
                risk_metrics,
                ai_predictions,
                optimization,
            )
        )

        # ------------------------------------------------------------------
        # RESULT
        # ------------------------------------------------------------------

        return PortfolioIntelligenceResult(
            analytics=analytics,
            risk_metrics=risk_metrics,
            ai_predictions=ai_predictions,
            optimization=optimization,
            recommendations=recommendations,
        )


