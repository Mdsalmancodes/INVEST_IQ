class MonteCarloUseCase:
    """
    Dedicated application use case for Monte Carlo portfolio simulation.

    Monte Carlo remains separate because:

        - num_runs is request-specific
        - horizon_days is request-specific
        - simulation can be computationally expensive
        - callers may want Monte Carlo without running the complete
          portfolio-intelligence pipeline
        - callers may want portfolio intelligence without Monte Carlo
    """

    def __init__(
        self,
        market_data_repository: MarketDataRepository,
        monte_carlo_service: MonteCarloService | None = None,
    ) -> None:
        """
        Initialize the Monte Carlo use case.
        """

        self._market_data_repository = market_data_repository

        self._monte_carlo_service = (
            monte_carlo_service
            if monte_carlo_service is not None
            else MonteCarloService()
        )

    async def execute(
        self,
        holdings: list[PortfolioHoldingInput],
        num_runs: int,
        horizon_days: int,
        lookback_days: int = 400,
    ) -> MonteCarloResult:
        """
        Execute Monte Carlo portfolio simulation.
        """

        # ------------------------------------------------------------------
        # VALIDATION
        # ------------------------------------------------------------------

        if lookback_days <= 0:
            raise ValueError(
                "lookback_days must be greater than zero."
            )

        if not holdings:
            raise ValueError(
                "At least one portfolio holding is required."
            )

        # ------------------------------------------------------------------
        # MARKET DATA
        # ------------------------------------------------------------------

        data = await fetch_holdings_returns(
            self._market_data_repository,
            holdings,
            lookback_days,
        )

        # ------------------------------------------------------------------
        # MONTE CARLO
        # ------------------------------------------------------------------

        return self._monte_carlo_service.simulate(
            data,
            num_runs=num_runs,
            horizon_days=horizon_days,
        )